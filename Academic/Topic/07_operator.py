#1 Assignment Operator
x = 5 #(=) assign a value
print(x)



#2 arithmetic operator
a = 2 + 5               #add - 7
b = 5 - 2               #sub - 3
c = 5 * 2               #mul - 10
d = 5 / 2               #div - 2.5 (float)
e = 5 % 2               #mod - 1
f = 5 ** 2              #powe - 25
g = 5 // 2              #div - 2 (interger)

print(a, b, c, d, e, f, g)




#3 boolean operator also called logical opeartor
a = True
b = False

print(a and b)      #False (and - both must be true)
print(a or b)       #True  (or - at least one must be true)
print(not b)        #True (swap)




#4 Relational operator
a = 10
b = 20

print(a == b)   # False
print(a != b)   # True
print(a > b)    # False
print(a < b)    # True
print(a >= 10)  # True
print(b <= 20)  # True
